package org.jumpstmnts;

public class SwitchEx {
public static void main(String[] args) {
	String ch="A";
	switch(ch)
	{
	case "A":
		System.out.println(1);
		//break;
	case 'B':
		System.out.println(3);
		//break;
	case 'C':
		System.out.println(5);
		
	default:
		System.out.println("error");
		
			
		
	}
}
}
